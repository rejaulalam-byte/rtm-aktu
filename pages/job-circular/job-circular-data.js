// Admin-entered text is inserted into the listing tables with template
// strings, so every field runs through this first - a `<` or `&` in a
// position name must print as text, never become markup. Same helper as
// escapeNewsHtml()/escapeEventHtml().
function escapeJobHtml(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// Today as YYYY-MM-DD in the visitor's local time zone - the same shape
// as `closingDate`, so the two compare as plain strings.
function jobCircularTodayIso() {
  const d = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

// A circular is effectively closed if the admin set it to CLOSED, or its
// closing date has passed (the closing day itself still counts as open).
// Worked out in the browser on every page view, so a circular closes on
// time with no admin action or re-publish - the site has no server-side
// scheduler. Used by job-circular.html (hides closed ones) and
// job-circular-all.html (shows Open/Closed).
function isJobCircularClosed(item) {
  if (item.status === 'CLOSED') return true;
  return Boolean(item.closingDate) && jobCircularTodayIso() > item.closingDate;
}
